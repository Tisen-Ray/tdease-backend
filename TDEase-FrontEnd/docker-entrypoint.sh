#!/bin/sh
set -e

# =============================================================================
# Runtime environment variable injection
#
# Vite embeds env vars at build time (VITE_*). For values that must be
# resolved at runtime (e.g. API URLs that differ per deployment), write
# them into /usr/share/nginx/html/env-config.js which the application's
# index.html loads before the app bundle.
#
# Add additional VITE_* vars below as needed.
# =============================================================================

CONFIG_FILE="/usr/share/nginx/html/env-config.js"

cat <<EOF > "$CONFIG_FILE"
// Runtime environment configuration - injected by docker-entrypoint.sh
// Do NOT edit this file directly; set environment variables on the container.

window.__RUNTIME_CONFIG__ = {
  VITE_API_BASE_URL: "${VITE_API_BASE_URL:-${VITE_API_URL:-}}",
  VITE_WS_URL: "${VITE_WS_URL:-}",
};
EOF

echo "[entrypoint] Wrote ${CONFIG_FILE}"

# Start Nginx in the foreground
exec nginx -g 'daemon off;'
